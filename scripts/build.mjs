import { readFile, readdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = fileURLToPath(new URL("..", import.meta.url));
const pkg = JSON.parse(await readFile(path.join(root, "package.json"), "utf8"));

const header = `/**
 * @name ReCord
 * @author leriart
 * @description A REPLACED-inspired terminal for Discord. Signal phosphor, pixel type, CRT grain.
 * @version ${pkg.version}
 * @license Apache-2.0
 * @source https://github.com/leriart/ReCord
 * @website https://leriart.github.io/ReCord/
 */`;

const settings = `/*
 * Self-contained build: fonts, icons and textures are embedded, so this file
 * works as an online theme link or as a local file in the themes folder.
 * Generated by scripts/build.mjs from src/. Do not edit by hand.
 *
 * To recolor the interface, override the accent in QuickCSS:
 *
 *     :root { --rl-accent: #e94221; }
 */`;

const order = file => (file.startsWith("01-") ? "00" : file.startsWith("00-") ? "01" : file.slice(0, 2));
const modules = (await readdir(path.join(root, "src")))
    .filter(file => file.endsWith(".css"))
    .sort((a, b) => order(a).localeCompare(order(b)) || a.localeCompare(b));

function compactSvg(svg) {
    const cells = [...svg.matchAll(/<rect x="(\d+)" y="(\d+)" width="(\d+)" height="(\d+)"\/>/g)].map(m => m.slice(1).map(Number));
    const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1];
    if (!cells.length || !viewBox || /<(path|circle|polygon|g fill="(?!#fff))/.test(svg)) return svg.replace(/\s+/g, " ").trim();

    const rows = new Map();
    for (const [x, y, w, h] of cells) {
        for (let row = y; row < y + h; row++) {
            if (!rows.has(row)) rows.set(row, new Set());
            for (let column = x; column < x + w; column++) rows.get(row).add(column);
        }
    }

    let d = "";
    for (const [row, columns] of [...rows].sort((a, b) => a[0] - b[0])) {
        const sorted = [...columns].sort((a, b) => a - b);
        for (let index = 0; index < sorted.length; index++) {
            const start = sorted[index];
            while (sorted[index + 1] === sorted[index] + 1) index++;
            const width = sorted[index] - start + 1;
            d += `M${start} ${row}h${width}v1h-${width}z`;
        }
    }
    return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" shape-rendering="crispEdges"><path fill="#fff" d="${d}"/></svg>`;
}

const mime = { ".svg": "image/svg+xml", ".png": "image/png", ".ttf": "font/ttf", ".gif": "image/gif" };
const cache = new Map();

async function dataUri(file) {
    if (cache.has(file)) return cache.get(file);
    const extension = path.extname(file);
    const buffer = await readFile(file);
    const uri =
        extension === ".svg"
            ? `data:image/svg+xml,${encodeURIComponent(compactSvg(buffer.toString("utf8"))).replace(/%20/g, " ").replace(/%3D/g, "=").replace(/%3A/g, ":").replace(/%2F/g, "/")}`
            : `data:${mime[extension]};base64,${buffer.toString("base64")}`;
    cache.set(file, uri);
    return uri;
}

const assets = new Map();
const parts = [];

for (const file of modules) {
    let css = await readFile(path.join(root, "src", file), "utf8");
    const matches = [...css.matchAll(/url\("(\.\.\/assets\/[^"]+)"\)/g)];
    for (const match of matches) {
        const target = path.join(root, "src", match[1]);
        const uri = await dataUri(target);
        if (path.extname(target) === ".ttf") {
            css = css.replace(match[0], `url("${uri}")`);
            continue;
        }
        const name = `--rl-asset-${path.basename(target).replace(/\.[^.]+$/, "")}`;
        assets.set(name, uri);
        css = css.replaceAll(match[0], `var(${name})`);
    }
    parts.push(`/* ${file} */\n\n${css.trim()}`);
}

const assetBlock = `:root {\n${[...assets].map(([name, uri]) => `    ${name}: url("${uri}");`).join("\n")}\n}`;
const bundle = [header, settings, "/* embedded assets */\n\n" + assetBlock, ...parts].join("\n\n") + "\n";

if (process.argv.includes("--check")) {
    const current = await readFile(path.join(root, "ReCord.theme.css"), "utf8").catch(() => "");
    if (current !== bundle) {
        console.error("error: ReCord.theme.css is out of date; run npm run build");
        process.exit(1);
    }
    console.log("ReCord.theme.css is up to date");
} else {
    await writeFile(path.join(root, "ReCord.theme.css"), bundle);
    console.log(`Built ReCord.theme.css v${pkg.version} (${modules.length} modules, ${assets.size} embedded assets, ${(bundle.length / 1024).toFixed(1)} KiB)`);
}
